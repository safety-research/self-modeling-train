"""
Module: prompt_attribution/training/data/dataset.py

Training dataset: JSONL loading, optional category balancing, train/test splitting.

Structure:
- TrainingRecord: Dataclass for a single training record
- TrainingDataset: Load, optionally balance, split into train/test
"""

import json
import logging
import random
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from prompt_attribution.training.config import DataConfig

logger = logging.getLogger(__name__)


def _resolve_answer(d: dict, side: str) -> str:
    """Resolve the correct answer for a training record.

    Prefers features_*[target_label_axis] (from target axis extraction,
    used for flip detection) over empirical_*_answer (from parse_answer(),
    generic parser that often disagrees with the axis extraction).

    Args:
        d: Raw JSONL dict.
        side: "baseline" or "lever".
    """
    axis = d.get("target_label_axis", "")
    features = d.get(f"features_{side}", {})
    if axis and features and axis in features:
        val = features[axis]
        if val and val != "(unknown)":
            return str(val)
    # Fallback to the stored field
    return d.get(f"empirical_{side}_answer", "")


@dataclass
class TrainingRecord:
    """A single training record from the corpus.

    Contains both the prompts for Phase 1 inference and the metadata
    needed for Phase 2 prompt building.
    """

    unique_id: str
    dataset_id: str
    example_idx: int
    question: str
    ground_truth_answer: str
    prompt_baseline: str
    prompt_lever: str
    lever_text: str
    baseline_text: str
    perturbation_type: str
    problem_edits: list[dict]
    category: str
    predicted_flip_probability: float
    empirical_flip_fraction: float | None
    target_label_axis: str
    answer_labels: list[dict]
    mechanism_name: str
    instruction_placement: str
    prompt_template: str
    context: str | None = None
    choices: list[str] | None = None
    capability_tags: list[str] = field(default_factory=list)
    # Empirical fields populated by ground truth inference
    empirical_flipped: bool | None = None
    empirical_flip_count: int | None = None
    empirical_n_runs: int | None = None
    empirical_baseline_answer: str = ""
    empirical_lever_answer: str = ""
    empirical_baseline_responses: list[str] = field(default_factory=list)
    empirical_lever_responses: list[str] = field(default_factory=list)
    verification_model: str = ""
    # Model that generated Phase 1 responses (distinct from verification_model which is the judge)
    inference_model: str = ""
    # Oracle reasoning (generated by Claude, replaces template reasoning in completions)
    oracle_reasoning: str = ""
    # LLM-summarized Phase 1 responses (for oracle_with_simulation format)
    summarized_baseline_response: str = ""
    summarized_lever_response: str = ""
    # Per-run summaries for n_stability>1 (one summary per stability run)
    summarized_baseline_responses: list[str] = field(default_factory=list)
    summarized_lever_responses: list[str] = field(default_factory=list)

    @classmethod
    def from_dict(cls, d: dict) -> "TrainingRecord":
        """Create TrainingRecord from a JSONL row dict."""
        return cls(
            unique_id=d["unique_id"],
            dataset_id=d.get("dataset_id", ""),
            example_idx=d.get("example_idx", 0),
            question=d.get("question", ""),
            ground_truth_answer=d.get("ground_truth_answer", ""),
            prompt_baseline=d["prompt_baseline"],
            prompt_lever=d["prompt_lever"],
            lever_text=d.get("lever_text", ""),
            baseline_text=d.get("baseline_text", ""),
            perturbation_type=d.get("perturbation_type", "instruction_add"),
            problem_edits=d.get("problem_edits", []),
            category=d.get("category", "unknown"),
            predicted_flip_probability=d.get("predicted_flip_probability", 0.5),
            empirical_flip_fraction=d.get("empirical_flip_fraction"),
            target_label_axis=d.get("target_label_axis", ""),
            answer_labels=d.get("answer_labels", []),
            mechanism_name=d.get("mechanism_name", ""),
            instruction_placement=d.get("instruction_placement", ""),
            prompt_template=d.get("prompt_template", ""),
            context=d.get("context"),
            choices=d.get("choices"),
            capability_tags=d.get("capability_tags", []),
            empirical_flipped=d.get("empirical_flipped"),
            empirical_flip_count=d.get("empirical_flip_count"),
            empirical_n_runs=d.get("empirical_n_runs"),
            # Prefer features_*[target_axis] over empirical_*_answer:
            # empirical_*_answer comes from parse_answer() (generic parser, often wrong)
            # features_*[target_axis] comes from the target axis extractor (correct)
            empirical_baseline_answer=_resolve_answer(d, "baseline"),
            empirical_lever_answer=_resolve_answer(d, "lever"),
            empirical_baseline_responses=d.get("empirical_baseline_responses", []),
            empirical_lever_responses=d.get("empirical_lever_responses", []),
            verification_model=d.get("verification_model", ""),
            inference_model=d.get("inference_model", ""),
            oracle_reasoning=d.get("oracle_reasoning", ""),
            summarized_baseline_response=d.get("summarized_baseline_response", ""),
            summarized_lever_response=d.get("summarized_lever_response", ""),
            summarized_baseline_responses=d.get("summarized_baseline_responses", []),
            summarized_lever_responses=d.get("summarized_lever_responses", []),
        )

    def to_dict(self) -> dict:
        """Convert back to dict for serialization."""
        return {
            "unique_id": self.unique_id,
            "dataset_id": self.dataset_id,
            "example_idx": self.example_idx,
            "question": self.question,
            "ground_truth_answer": self.ground_truth_answer,
            "prompt_baseline": self.prompt_baseline,
            "prompt_lever": self.prompt_lever,
            "lever_text": self.lever_text,
            "baseline_text": self.baseline_text,
            "perturbation_type": self.perturbation_type,
            "problem_edits": self.problem_edits,
            "category": self.category,
            "predicted_flip_probability": self.predicted_flip_probability,
            "empirical_flip_fraction": self.empirical_flip_fraction,
            "target_label_axis": self.target_label_axis,
            "answer_labels": self.answer_labels,
            "mechanism_name": self.mechanism_name,
            "instruction_placement": self.instruction_placement,
            "prompt_template": self.prompt_template,
            "context": self.context,
            "choices": self.choices,
            "capability_tags": self.capability_tags,
            "empirical_flipped": self.empirical_flipped,
            "empirical_flip_count": self.empirical_flip_count,
            "empirical_n_runs": self.empirical_n_runs,
            "empirical_baseline_answer": self.empirical_baseline_answer,
            "empirical_lever_answer": self.empirical_lever_answer,
            "empirical_baseline_responses": self.empirical_baseline_responses,
            "empirical_lever_responses": self.empirical_lever_responses,
            "verification_model": self.verification_model,
            "inference_model": self.inference_model,
            "oracle_reasoning": self.oracle_reasoning,
            "summarized_baseline_response": self.summarized_baseline_response,
            "summarized_lever_response": self.summarized_lever_response,
            "summarized_baseline_responses": self.summarized_baseline_responses,
            "summarized_lever_responses": self.summarized_lever_responses,
        }


class TrainingDataset:
    """Load, optionally balance, and split training data into train/test.

    Supports two balancing strategies (controlled by DataConfig):
    - balance_by_category: Undersample categories to match smallest (drops data)
    - balance_by_flip_label: Keep all data, weight loss by inverse flip-label
      frequency (uses base model GT, not critic predictions)

    Usage:
        dataset = TrainingDataset(config)
        dataset.load()
        for batch in dataset.get_train_batches(epoch=0, batch_size=8):
            ...
    """

    def __init__(self, config: DataConfig) -> None:
        self.config = config
        self.all_records: list[TrainingRecord] = []
        self.train_records: list[TrainingRecord] = []
        self.test_records: list[TrainingRecord] = []
        # Per-record loss weight multiplier (keyed by unique_id)
        # Used when balance_by_flip_label=True to weight loss by inverse class frequency
        self._sample_weights: dict[str, float] = {}

    # Fixed seed for train/test split — NEVER varies across runs.
    # Training randomness (batch order, LoRA init) uses the config seed instead.
    SPLIT_SEED = 42

    def load(self, n_samples: int = 0) -> None:
        """Load records from JSONL, optionally subsample, balance, and split.

        Args:
            n_samples: If > 0, only use this many records (for debugging).
        """
        path = Path(self.config.training_data_path)
        logger.info(f"Loading training data from {path}")

        records: list[TrainingRecord] = []
        with open(path) as f:
            for line in f:
                row = json.loads(line.strip())
                records.append(TrainingRecord.from_dict(row))

        logger.info(f"Loaded {len(records)} records")

        # Debug subsample (fixed seed so same records across runs)
        if n_samples > 0:
            rng = random.Random(self.SPLIT_SEED)
            records = rng.sample(records, min(n_samples, len(records)))
            logger.info(f"Subsampled to {len(records)} records")

        # Overlay cached base model ground truth if available
        if self.config.base_model_gt_cache_path:
            records = self._overlay_gt_cache(records)

        # Filter to records with ground truth
        records_with_gt = [r for r in records if r.empirical_flip_fraction is not None]
        records_without_gt = len(records) - len(records_with_gt)
        if records_without_gt > 0:
            logger.warning(
                f"Skipping {records_without_gt} records without empirical_flip_fraction"
            )
        records = records_with_gt

        # Filter out records without answer_labels — their flip labels are
        # determined by raw string comparison (not LLM judge extraction),
        # which is extremely noisy (~67% false flip rate vs ~16% with labels)
        records_with_labels = [r for r in records if r.answer_labels]
        n_no_labels = len(records) - len(records_with_labels)
        if n_no_labels > 0:
            logger.warning(
                f"Skipping {n_no_labels} records without answer_labels "
                f"(unreliable flip labels from raw string comparison)"
            )
        records = records_with_labels

        # Category balancing (drops data — legacy approach)
        if self.config.balance_by_category:
            records = self._balance_by_category(records)

        self.all_records = records

        # Train/test split (uses SPLIT_SEED=42, never varies across runs)
        self._split_train_test()

        # Save split for reproducibility
        self._save_split_ids()

        # Compute class weights for flip label balancing (keeps all data)
        if self.config.balance_by_flip_label:
            self._compute_flip_label_weights()

        self._log_stats()

    def get_sample_weight(self, record: TrainingRecord) -> float:
        """Get the loss weight multiplier for a training record.

        Returns 1.0 if no class weighting is configured.
        """
        return self._sample_weights.get(record.unique_id, 1.0)

    def _compute_flip_label_weights(self) -> None:
        """Compute per-sample weights based on GT flip label frequency.

        Uses empirical_flip_fraction (base model ground truth) to determine
        flip vs no-flip class. Weights are inverse class frequency so the
        minority class gets higher weight.

        Weight formula: w_class = N_total / (2 * N_class)
        This gives equal effective contribution from each class.
        """
        n_flip = sum(1 for r in self.train_records if (r.empirical_flip_fraction or 0) >= 0.5)
        n_no_flip = len(self.train_records) - n_flip
        n_total = len(self.train_records)

        if n_flip == 0 or n_no_flip == 0:
            logger.warning(
                f"Cannot compute flip label weights: flip={n_flip}, no_flip={n_no_flip}. "
                "All weights set to 1.0."
            )
            return

        # Inverse frequency: w = N_total / (2 * N_class)
        w_flip = n_total / (2 * n_flip)
        w_no_flip = n_total / (2 * n_no_flip)

        logger.info(
            f"Flip label class weights: flip={n_flip} (w={w_flip:.3f}), "
            f"no_flip={n_no_flip} (w={w_no_flip:.3f})"
        )

        for r in self.train_records:
            is_flip = (r.empirical_flip_fraction or 0) >= 0.5
            self._sample_weights[r.unique_id] = w_flip if is_flip else w_no_flip

    def _overlay_gt_cache(self, records: list[TrainingRecord]) -> list[TrainingRecord]:
        """Overlay cached base model ground truth onto records.

        Loads a previously-saved GT cache JSONL (keyed by unique_id) and updates
        records with cached empirical_flip_fraction and related fields. This avoids
        re-running Phase 1 inference when the same base model GT has been computed before.

        If the cache file doesn't exist, logs a warning and returns records unchanged.
        """
        assert self.config.base_model_gt_cache_path is not None
        cache_path = Path(self.config.base_model_gt_cache_path)
        if not cache_path.exists():
            logger.warning(
                f"GT cache file not found: {cache_path}. "
                "Records will use their existing empirical_flip_fraction values. "
                "Run Phase 1 GT inference and save to this path to enable caching."
            )
            return records

        logger.info(f"Loading base model GT cache from {cache_path}")
        gt_by_id: dict[str, dict] = {}
        with open(cache_path) as f:
            for line in f:
                row = json.loads(line.strip())
                uid = row.get("unique_id", "")
                if uid:
                    gt_by_id[uid] = row

        n_matched = 0
        gt_fields = [
            "empirical_flip_fraction", "empirical_flipped",
            "empirical_flip_count", "empirical_n_runs",
            "empirical_baseline_answer", "empirical_lever_answer",
            "empirical_baseline_responses", "empirical_lever_responses",
            "inference_model",
            "oracle_reasoning",
            "summarized_baseline_response",
            "summarized_lever_response",
            "summarized_baseline_responses",
            "summarized_lever_responses",
        ]

        for record in records:
            if record.unique_id in gt_by_id:
                cached = gt_by_id[record.unique_id]
                for field in gt_fields:
                    if field in cached:
                        setattr(record, field, cached[field])
                n_matched += 1

        logger.info(
            f"GT cache overlay: {n_matched}/{len(records)} records matched "
            f"({len(gt_by_id)} entries in cache)"
        )
        return records

    def _balance_by_category(self, records: list[TrainingRecord]) -> list[TrainingRecord]:
        """Undersample majority categories to match the smallest category."""
        by_category: dict[str, list[TrainingRecord]] = defaultdict(list)
        for r in records:
            by_category[r.category].append(r)

        min_count = min(len(v) for v in by_category.values())
        logger.info(
            f"Balancing categories: {', '.join(f'{k}={len(v)}' for k, v in by_category.items())} "
            f"→ {min_count} each"
        )

        rng = random.Random(self.config.seed)
        balanced: list[TrainingRecord] = []
        for cat, cat_records in by_category.items():
            balanced.extend(rng.sample(cat_records, min_count))

        rng.shuffle(balanced)
        return balanced

    def _split_train_test(self) -> None:
        """Split records into train and test sets.

        If eval_data_path is set, all records from training_data_path become
        train_records, and test_records are loaded from eval_data_path (with
        the same seed/test_split applied to that file). This avoids double-
        splitting when training_data_path is a pre-filtered subset (e.g.,
        contrastive pairs) but eval should use the full corpus's test set.
        """
        if self.config.eval_data_path:
            # All training records are used for training (no split)
            self.train_records = list(self.all_records)

            # Load eval data separately and extract test split from it
            eval_path = Path(self.config.eval_data_path)
            logger.info(f"Loading eval data from {eval_path}")
            eval_records: list[TrainingRecord] = []
            with open(eval_path) as f:
                for line in f:
                    eval_records.append(TrainingRecord.from_dict(json.loads(line.strip())))

            # Apply same GT cache overlay if available
            if self.config.base_model_gt_cache_path:
                eval_records = self._overlay_gt_cache(eval_records)

            # Filter same as training data
            eval_records = [r for r in eval_records if r.empirical_flip_fraction is not None]
            eval_records = [r for r in eval_records if r.answer_labels]

            # Apply test_split to eval data (fixed seed for reproducible split)
            rng = random.Random(self.SPLIT_SEED)
            indices = list(range(len(eval_records)))
            rng.shuffle(indices)
            n_test = int(len(indices) * self.config.test_split)
            test_indices = set(indices[:n_test])
            self.test_records = [
                r for i, r in enumerate(eval_records) if i in test_indices
            ]
            logger.info(f"Eval data: {len(eval_records)} total → {len(self.test_records)} test records")
        else:
            # Standard split: partition all_records into train/test (fixed seed)
            rng = random.Random(self.SPLIT_SEED)
            indices = list(range(len(self.all_records)))
            rng.shuffle(indices)

            n_test = int(len(indices) * self.config.test_split)
            test_indices = set(indices[:n_test])

            self.train_records = [
                r for i, r in enumerate(self.all_records) if i not in test_indices
            ]
            self.test_records = [
                r for i, r in enumerate(self.all_records) if i in test_indices
            ]

    def _save_split_ids(self) -> None:
        """Save train/test split IDs to a JSON file next to the training data.

        File is saved once per unique (training_data_path, test_split, SPLIT_SEED)
        combination. Subsequent loads verify the split matches.
        """
        split_file = self.config.training_data_path.parent / "train_test_split.json"
        test_ids = sorted(r.unique_id for r in self.test_records)
        train_ids = sorted(r.unique_id for r in self.train_records)

        split_data = {
            "split_seed": self.SPLIT_SEED,
            "test_split": self.config.test_split,
            "n_train": len(train_ids),
            "n_test": len(test_ids),
            "test_ids": test_ids,
        }

        if split_file.exists():
            # Verify existing split matches
            existing = json.loads(split_file.read_text())
            if set(existing.get("test_ids", [])) != set(test_ids):
                logger.warning(
                    f"Split mismatch! Existing {split_file} has {existing.get('n_test', '?')} test, "
                    f"current has {len(test_ids)}. This may indicate a seed or data change."
                )
            else:
                logger.info(f"Split verified: matches {split_file}")
            return

        split_file.write_text(json.dumps(split_data, indent=2))
        logger.info(f"Saved train/test split to {split_file} ({len(train_ids)} train, {len(test_ids)} test)")

    def _log_stats(self) -> None:
        """Log dataset statistics including flip label distribution."""
        logger.info(f"Dataset: {len(self.train_records)} train, {len(self.test_records)} test")

        for split_name, split_records in [("train", self.train_records), ("test", self.test_records)]:
            cats = defaultdict(int)
            ptypes = defaultdict(int)
            n_flip = 0
            n_no_flip = 0
            for r in split_records:
                cats[r.category] += 1
                ptypes[r.perturbation_type] += 1
                if (r.empirical_flip_fraction or 0) >= 0.5:
                    n_flip += 1
                else:
                    n_no_flip += 1
            logger.info(
                f"  {split_name} categories: {dict(cats)}"
            )
            logger.info(
                f"  {split_name} perturbation types: {dict(ptypes)}"
            )
            logger.info(
                f"  {split_name} flip labels: flip={n_flip}, no_flip={n_no_flip} "
                f"(ratio={n_flip / max(1, n_flip + n_no_flip):.2%})"
            )

        if self._sample_weights:
            weights = list(self._sample_weights.values())
            logger.info(
                f"  Class weights active: min={min(weights):.3f}, "
                f"max={max(weights):.3f}, mean={sum(weights) / len(weights):.3f}"
            )

    def get_train_batches(
        self, epoch: int, batch_size: int
    ) -> list[list[TrainingRecord]]:
        """Get shuffled training batches for one epoch.

        Args:
            epoch: Current epoch (used for deterministic shuffling).
            batch_size: Number of records per batch.

        Returns:
            List of batches, each a list of TrainingRecord.
        """
        rng = random.Random(self.config.seed + epoch)
        indices = list(range(len(self.train_records)))
        rng.shuffle(indices)

        batches = []
        for start in range(0, len(indices), batch_size):
            batch_indices = indices[start : start + batch_size]
            batch = [self.train_records[i] for i in batch_indices]
            batches.append(batch)

        return batches
